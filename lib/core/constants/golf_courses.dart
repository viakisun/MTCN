  static List<GolfCourse> getCoursesByPriceRange({
    int? minPrice,
    int? maxPrice,
  }) {
    return koreanCourses.where((course) {
      if (course.avgGreenFee == null) return false;
      if (minPrice != null && course.avgGreenFee! < minPrice) return false;
      if (maxPrice != null && course.avgGreenFee! > maxPrice) return false;
      return true;
    }).toList();
  }
