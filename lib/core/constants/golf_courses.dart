/// 골프장 모델
class GolfCourse {
  final String name;
  final String address;
  final String region;
  final int? avgGreenFee;

  const GolfCourse({
    required this.name,
    required this.address,
    required this.region,
    this.avgGreenFee,
  });

  /// 가격 포맷팅
  String get formattedPrice {
    if (avgGreenFee == null) return '가격 정보 없음';
    return '${(avgGreenFee! / 10000).toStringAsFixed(0)}만원';
  }

  /// 주소 단축 표시
  String get shortAddress {
    final parts = address.split(' ');
    if (parts.length >= 2) {
      return '${parts[0]} ${parts[1]}';
    }
    return address;
  }

  @override
  String toString() => name;

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is GolfCourse && other.name == name;
  }

  @override
  int get hashCode => name.hashCode;
}
